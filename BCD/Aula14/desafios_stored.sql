    DECLARE V_QUANTIDADE INT;

    SELECT QUANTIDADE
    INTO V_QUANTIDADE
    FROM ESTOQUE
    WHERE ID_PRODUTO = P_ID_PRODUTO;

    SELECT V_QUANTIDADE AS QUANTIDADE_ESTOQUE;
END $$
