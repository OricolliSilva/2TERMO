-- 9. criar_pedido(IN p_id_cliente INT, OUT p_id_pedido INT)
DELIMITER $$
CREATE PROCEDURE CRIAR_PEDIDO(
    IN P_ID_CLIENTE INT,
    OUT P_ID_PEDIDO INT
)
BEGIN
    START TRANSACTION;

    INSERT INTO PEDIDO (
        ID_CLIENTE,
        DATA_PEDIDO,
        STATUS_PEDIDO
    )
    VALUES (
        P_ID_CLIENTE, NOW(), 'ABERTO'
    );

    SET P_ID_PEDIDO = LAST_INSERT_ID();

    COMMIT;
END $$
DELIMITER ;

